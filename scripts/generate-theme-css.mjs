import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";

async function loadSource(relativePath) {
  const source = await readFile(new URL(relativePath, import.meta.url), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 }
  });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
}

const [{ themeTokens }, { fontStyleTokens }, { toCssVariables }] = await Promise.all([
  loadSource("../src/theme/theme.ts"),
  loadSource("../src/system/fonts.ts"),
  loadSource("../src/theme/cssVariables.ts")
]);

function rule(selector, declarations) {
  const body = Object.entries(declarations)
    .filter(([, value]) => value !== undefined)
    .map(([property, value]) => `  ${property}: ${value};`)
    .join("\n");
  return `${selector} {\n${body}\n}`;
}

const rules = ["/* Generated by scripts/generate-theme-css.mjs. Edit the TypeScript theme sources. */"];
for (const [theme, modes] of Object.entries(themeTokens)) {
  for (const [mode, tokens] of Object.entries(modes)) {
    const { fontDisplay, fontBody, fontDisplayLetterSpacing, ...colors } = tokens;
    rules.push(rule(`.mx-theme[data-mx-theme="${theme}"][data-mx-mode="${mode}"]`, {
      ...toCssVariables(colors),
      "color-scheme": mode
    }));
    const scope = `[data-mx-color="${theme}"][data-mx-color-mode="${mode}"]`;
    rules.push(rule(`.mx-link${scope}`, { color: tokens.buttonGhostText }));
    rules.push(rule(`.mx-card${scope}, .mx-header${scope}, .mx-text${scope}`, { color: tokens.text }));
    rules.push(rule(`.mx-card${scope}[data-mx-appearance="solid"]`, {
      "background-color": tokens.surface
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="primary"]`, {
      "background-color": tokens.buttonPrimaryBg, color: tokens.buttonPrimaryText
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="primary"]:hover:not(:disabled)`, {
      "background-color": tokens.buttonPrimaryBgHover
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="secondary"]`, {
      "background-color": tokens.buttonSecondaryBg, color: tokens.buttonSecondaryText
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="secondary"]:hover:not(:disabled)`, {
      "background-color": tokens.buttonSecondaryBgHover
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="ghost"]`, {
      "border-color": tokens.buttonGhostBorder, color: tokens.buttonGhostText
    }));
    rules.push(rule(`.mx-button${scope}[data-mx-variant="ghost"]:hover:not(:disabled)`, {
      "background-color": tokens.buttonGhostBgHover
    }));
  }
}
for (const [font, tokens] of Object.entries(fontStyleTokens)) {
  rules.push(rule(`.mx-theme[data-mx-font-style="${font}"]`, toCssVariables(tokens)));
  rules.push(rule(`.mx-demo-font[data-demo-font="${font}"]`, {
    "font-family": tokens.fontDisplay,
    "letter-spacing": tokens.fontDisplayLetterSpacing
  }));
}
await writeFile(new URL("../src/theme/themes.css", import.meta.url), `${rules.join("\n\n")}\n`);
